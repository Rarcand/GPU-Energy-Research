#!/usr/bin/env python3
"""Matched representation, family sharing, and strict workload/device transfer tests.

Run on CPU; no benchmark timing labels are generated by this script. Input files
are explicitly selected and hashed. Splits group semantic shapes across dtypes,
configurations and devices. Failed attempts consume top-B replay budget.
"""
import argparse
import copy
import csv
import hashlib
import json
import math
import os
import platform
import random
import time
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
import torch
from torch import nn
from sklearn.ensemble import HistGradientBoostingRegressor
from scipy.stats import spearmanr

FAMILIES = ('attention', 'conv2d', 'cross_entropy', 'gather', 'gemm',
            'residual_layernorm', 'softmax')
SHAPES = ('m', 'n', 'k', 'rows', 'reduction_width', 'batch', 'height',
          'in_channels', 'out_channels', 'kernel', 'stride', 'heads', 'q_len',
          'kv_len', 'head_dim', 'causal', 'vocab', 'lookups', 'width')
ARCH = ('compute_capability', 'sm_count', 'total_memory_bytes', 'warp_size',
        'max_threads_per_block', 'max_threads_per_sm', 'shared_memory_per_block_bytes',
        'shared_memory_per_sm_bytes', 'registers_per_sm', 'l2_cache_bytes',
        'memory_bus_width_bits', 'max_sm_clock_mhz', 'max_memory_clock_mhz', 'power_limit_w')
CONFIG = ('block_m', 'block_n', 'block_k', 'group_m', 'block_size',
          'block_multiplier', 'block_rows', 'block_cols', 'num_warps', 'num_stages')


def number(value):
    if str(value).lower() in ('true', 'false'):
        return float(str(value).lower() == 'true')
    try:
        value = float(value)
        return value if math.isfinite(value) else None
    except (ValueError, TypeError):
        return None


def normalized(row):
    row = dict(row)
    for field in ('workload_features_json', 'config_features_json'):
        row.update(json.loads(row.get(field) or '{}'))
    shape = {key: number(row.get(key)) for key in SHAPES if number(row.get(key)) is not None}
    if row.get('locality'):
        shape['locality'] = row['locality']
    family = row['kernel_family']
    if not shape:
        raise ValueError('Missing shape descriptors: ' + row.get('workload_id', ''))
    group = family + ':' + json.dumps(shape, sort_keys=True)
    task = group + ':' + row['dtype']
    config = {key: number(row.get(key)) for key in CONFIG if number(row.get(key)) is not None}
    device = 'H100' if 'H100' in row['gpu_name'].upper() else 'A100'
    latency = number(row.get('latency_median_ms'))
    valid = str(row.get('is_valid') or row.get('correctness_pass')).lower() in ('1', 'true')
    valid = valid and row.get('status', 'ok') == 'ok' and latency is not None and latency > 0
    row.update(_group=group, _task=task, _device=device,
               _key=task + ':' + json.dumps(config, sort_keys=True),
               _y=latency if valid else float('nan'))
    return row


def load(paths):
    rows, manifest, seen, duplicates = [], [], set(), 0
    for path in sorted(paths):
        manifest.append({'path': str(path), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
        with path.open(newline='') as stream:
            for raw in csv.DictReader(stream):
                row = normalized(raw)
                key = (row['_device'], row['_key'])
                if key in seen:
                    duplicates += 1
                    continue
                seen.add(key)
                row['_file'] = str(path)
                rows.append(row)
    return rows, {'files': manifest, 'duplicates_dropped': duplicates,
                  'attempts': len(rows), 'valid': sum(np.isfinite(r['_y']) for r in rows),
                  'families': dict(Counter(r['kernel_family'] for r in rows))}


def split_groups(rows, seed=61205):
    by_family, assignment = defaultdict(set), {}
    for row in rows:
        by_family[row['kernel_family']].add(row['_group'])
    rng = random.Random(seed)
    for family, groups in sorted(by_family.items()):
        groups = sorted(groups)
        rng.shuffle(groups)
        if len(groups) < 5:
            raise ValueError('Need >=5 shapes per family: ' + family)
        count = max(1, round(.2 * len(groups)))
        for i, group in enumerate(groups):
            assignment[group] = 'test' if i < count else 'validation' if i < 2 * count else 'train'
    return assignment


def matrices(rows):
    result = []
    for fields in (ARCH, SHAPES, CONFIG):
        values, masks = [], []
        for row in rows:
            raw = [number(row.get(key)) for key in fields]
            values.append([math.log1p(max(v, 0)) if v is not None else 0. for v in raw])
            masks.append([float(v is not None) for v in raw])
        result.append(np.column_stack((values, masks)).astype('float32'))
    # The same semantic one-hot features go to both neural models and the tree.
    categories = [('kernel_family', FAMILIES), ('dtype', ('float16', 'bfloat16')),
                  ('locality', ('uniform', 'clustered', 'repeated'))]
    extras = np.asarray([[float(row.get(key) == value) for key, values in categories
                          for value in values] for row in rows], dtype='float32')
    result[1] = np.column_stack((result[1], extras))
    return result


class Processor:
    def fit(self, arrays, indices, y):
        self.stats = []
        for array in arrays:
            mean, std = array[indices].mean(0), array[indices].std(0)
            # Source-constant columns use relative scaling rather than explosive
            # unit differences when the target architecture is first presented.
            std = np.where(std < 1e-6, np.maximum(np.abs(mean), 1.), std)
            self.stats.append((mean, std))
        self.mean = float(np.log(y[indices]).mean())
        self.std = max(float(np.log(y[indices]).std()), 1e-6)
        return self

    def transform(self, arrays):
        return [torch.from_numpy(((a-m)/s).astype('float32'))
                for a, (m, s) in zip(arrays, self.stats)]


class Network(nn.Module):
    def __init__(self, sizes, kind):
        super().__init__()
        self.kind = kind
        self.branches = nn.ModuleList()
        if kind == 'three':
            for size in sizes:
                self.branches.append(nn.Sequential(nn.Linear(size, 64), nn.ReLU(),
                    nn.LayerNorm(64), nn.Dropout(.05), nn.Linear(64, 16), nn.ReLU()))
            self.fusion = nn.Sequential(nn.Linear(48, 128), nn.ReLU(), nn.Dropout(.1),
                                       nn.Linear(128, 64), nn.ReLU(), nn.Linear(64, 1))
        elif kind == 'flat':
            # Choose width without looking at labels to approximately match the
            # three-encoder model's parameter count, preserving a similar depth.
            target = sum((s+1)*64 + 128 + 65*16 for s in sizes) + 49*128 + 129*64 + 65
            total = sum(sizes)
            width = min(range(16, 257), key=lambda h: abs(
                (total+1)*h + 2*h + (h+1)*h + 2*h + (h+1)*64 + 65 - target))
            self.fusion = nn.Sequential(nn.Linear(total, width), nn.ReLU(),
                nn.LayerNorm(width), nn.Dropout(.05), nn.Linear(width, width),
                nn.ReLU(), nn.LayerNorm(width), nn.Dropout(.1),
                nn.Linear(width, 64), nn.ReLU(), nn.Linear(64, 1))
        else:
            raise ValueError(kind)

    def forward(self, arrays):
        if self.kind == 'three':
            arrays = [branch(a) for branch, a in zip(self.branches, arrays)]
        return self.fusion(torch.cat(arrays, 1)).squeeze(1)


def predict(model, arrays, processor):
    model.eval()
    with torch.no_grad():
        log = torch.cat([model([a[i:i+2048] for a in arrays])
                         for i in range(0, len(arrays[0]), 2048)]).numpy()
    return np.exp(np.clip(log * processor.std + processor.mean, -20, 20))


def fit(arrays, y, train, validation, kind, seed, args, initial=None, fixed_epochs=None, *, model_factory=Network):
    assert len(train) and len(validation)
    assert not set(train) & set(validation)
    torch.manual_seed(seed)
    started = time.perf_counter()
    if initial is None:
        processor = Processor().fit(arrays, train, y)
        model = model_factory([a.shape[1] for a in arrays], kind)
    else:
        model, processor = copy.deepcopy(initial)
    x = processor.transform(arrays)
    labels = torch.from_numpy(((np.log(np.where(np.isfinite(y), y, 1.)) - processor.mean)
                              / processor.std).astype('float32'))
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=1e-4)
    lossfn = nn.SmoothL1Loss()
    best, best_score, stale, best_epoch = None, float('inf'), 0, 0
    rng = np.random.default_rng(seed)
    for epoch in range(1, (fixed_epochs or args.epochs) + 1):
        model.train()
        order = rng.permutation(train)
        for begin in range(0, len(order), args.batch_size):
            index = order[begin:begin+args.batch_size]
            optimizer.zero_grad(set_to_none=True)
            loss = lossfn(model([a[index] for a in x]), labels[index])
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 10.)
            optimizer.step()
        model.eval()
        with torch.no_grad():
            p = np.exp(np.clip(model([a[validation] for a in x]).numpy()
                               * processor.std + processor.mean, -20, 20))
        score = float(np.mean(np.abs(p/y[validation]-1)))
        if score < best_score:
            best, best_score, stale, best_epoch = copy.deepcopy(model.state_dict()), score, 0, epoch
        else:
            stale += 1
        if fixed_epochs is None and stale >= args.patience:
            break
    model.load_state_dict(best)
    return (model, processor), predict(model, x, processor), {
        'epochs_run': epoch, 'best_epoch': best_epoch,
        'validation_mape_pct': best_score * 100, 'train_rows': len(train),
        'validation_rows': len(validation), 'parameters': sum(p.numel() for p in model.parameters()),
        'training_seconds': time.perf_counter()-started}


def scores(rows, indices, predicted, budgets=(1, 2, 4, 8)):
    y = np.asarray([r['_y'] for r in rows])
    task_indices, out = defaultdict(list), []
    for i in indices:
        task_indices[(rows[i]['_device'], rows[i]['_task'])].append(i)
    for (device, task), ix in sorted(task_indices.items()):
        ix = np.asarray(ix)
        good = ix[np.isfinite(y[ix])]
        if not len(good):
            continue
        rho = float(spearmanr(y[good], predicted[good]).statistic) if (
            len(good)>1 and np.ptp(y[good])>0 and np.ptp(predicted[good])>0) else None
        if rho is not None and not math.isfinite(rho):
            rho = None
        entry = {'device': device, 'task': task, 'group': rows[ix[0]]['_group'],
                 'family': rows[ix[0]]['kernel_family'], 'attempts': len(ix), 'valid': len(good),
                 'mape_pct': float(100*np.mean(np.abs(predicted[good]/y[good]-1))),
                 'mae_us': float(1000*np.mean(np.abs(predicted[good]-y[good]))), 'spearman': rho}
        ordered = ix[np.argsort(predicted[ix], kind='stable')]
        for budget in budgets:
            selected = ordered[:budget]
            successful = selected[np.isfinite(y[selected])]
            entry['effective_b'+str(budget)] = len(selected)
            entry['invalid_b'+str(budget)] = int(np.sum(~np.isfinite(y[selected])))
            entry['regret_b'+str(budget)] = (float(y[successful].min()/y[good].min()-1)
                                            if len(successful) else None)
            entry['success5_b'+str(budget)] = float(len(successful)>0 and
                y[successful].min() <= 1.05*y[good].min())
        out.append(entry)
    return out


def calibration(rows, pool, count, seed):
    by_family = defaultdict(list)
    for i in pool:
        by_family[rows[i]['kernel_family']].append(i)
    rng = random.Random(seed)
    for values in by_family.values():
        rng.shuffle(values)
    selected = []
    while len(selected) < count:
        moved = False
        for family in sorted(by_family):
            if by_family[family] and len(selected)<count:
                selected.append(by_family[family].pop())
                moved = True
        if not moved:
            raise ValueError('Calibration budget exceeds pool')
    return np.asarray(selected, dtype=int)


def save_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix('.tmp')
    temporary.write_text(json.dumps(value, indent=2, allow_nan=False,
                                   default=lambda v: v.item() if isinstance(v,np.generic) else str(v)))
    temporary.replace(path)


def run_suite(rows, name, args):
    arrays = matrices(rows)
    y = np.asarray([r['_y'] for r in rows])
    assignment = split_groups(rows)
    indices = {label: np.asarray([i for i,r in enumerate(rows) if assignment[r['_group']]==label
                                 and (label=='test' or np.isfinite(y[i]))], dtype=int)
               for label in ('train', 'validation', 'test')}
    save_json(args.output / (name+'_split.json'), {'assignment': assignment,
              'rows': {k: len(v) for k,v in indices.items()}, 'split_seed': 61205})
    results = []

    def record(seed, method, pred, info, test=None, **context):
        entry = {'suite': name, 'seed': seed, 'method': method, **context,
                 'training': info, 'tasks': scores(rows, indices['test'] if test is None else test, pred)}
        results.append(entry)
        # Individual records preserve every completed comparison independently.
        key = '-'.join(str(context[k]) for k in sorted(context))
        save_json(args.output / 'runs' / ('%s-%s-%s-%s.json' % (name, seed, method, key)), entry)
        selected = indices['test'] if test is None else test
        prediction_file = args.output/'predictions'/('%s-%s-%s-%s.csv' % (name,seed,method,key))
        prediction_file.parent.mkdir(parents=True,exist_ok=True)
        with prediction_file.open('w',newline='') as stream:
            writer = csv.writer(stream)
            writer.writerow(['device','group','task','candidate','valid','latency_ms','prediction_ms'])
            for i in selected:
                writer.writerow([rows[i]['_device'],rows[i]['_group'],rows[i]['_task'],rows[i]['_key'],
                    bool(np.isfinite(y[i])),y[i] if np.isfinite(y[i]) else '',float(pred[i])])
        print(name, seed, method, context, 'finished', flush=True)

    if name == 'a100_seven':
        for seed in args.seeds:
            for kind in ('three', 'flat'):
                _, pred, info = fit(arrays, y, indices['train'], indices['validation'], kind, seed, args)
                record(seed, kind, pred, info)
            pred = np.zeros(len(rows))
            infos = {}
            for family in sorted(set(r['kernel_family'] for r in rows)):
                family_mask = np.asarray([r['kernel_family']==family for r in rows])
                # A family-specific model uses the identical features, architecture,
                # optimizer and total available labels for that family; all seven
                # fits together consume the same dataset as the shared fit.
                _, p, info = fit(arrays, y, indices['train'][family_mask[indices['train']]],
                    indices['validation'][family_mask[indices['validation']]], 'three', seed, args)
                pred[family_mask] = p[family_mask]
                infos[family] = info
            record(seed, 'separate_families', pred, infos)
            # Equal small validation-selected grid, never selected on test labels.
            processor = Processor().fit(arrays, indices['train'], y)
            x = np.column_stack([t.numpy() for t in processor.transform(arrays)])
            best_score, best_tree, best_cfg = float('inf'), None, None
            for leaves, l2 in ((15, 1.), (31, 1.), (31, 10.)):
                tree = HistGradientBoostingRegressor(max_iter=args.epochs,
                    max_leaf_nodes=leaves, l2_regularization=l2, early_stopping=False,
                    random_state=seed).fit(x[indices['train']], np.log(y[indices['train']]))
                p = np.exp(tree.predict(x[indices['validation']]))
                score = np.mean(np.abs(p/y[indices['validation']]-1))
                if score<best_score:
                    best_score, best_tree, best_cfg = score, tree, (leaves,l2)
            record(seed, 'boosted_tree', np.exp(best_tree.predict(x)),
                   {'grid': [(15,1.),(31,1.),(31,10.)], 'selected': best_cfg,
                    'validation_mape_pct': best_score*100})
            random_pred = np.random.default_rng(seed).random(len(rows))
            record(seed, 'random_search', random_pred, {})
    else:
        for target in ('H100', 'A100'):
            is_target = np.asarray([r['_device']==target for r in rows])
            train = indices['train'][~is_target[indices['train']]]
            val = indices['validation'][~is_target[indices['validation']]]
            test = indices['test'][is_target[indices['test']]]
            for seed in args.seeds:
                initial, pred, info = fit(arrays, y, train, val, 'three', seed, args)
                record(seed, 'zero_shot', pred, info, test, target=target, budget=0)
                for budget in args.budgets:
                    nv = max(3, round(budget*.25))
                    caltrain = calibration(rows, indices['train'][is_target[indices['train']]],
                                           budget-nv, seed)
                    calval = calibration(rows, indices['validation'][is_target[indices['validation']]],
                                         nv, seed)
                    for method, start in (('transfer', initial), ('target_only', None)):
                        _, pred, info = fit(arrays, y, caltrain, calval, 'three', seed, args, initial=start)
                        info['calibration_indices'] = {'train': caltrain.tolist(), 'validation': calval.tolist()}
                        record(seed, method, pred, info, test, target=target, budget=budget)
    return results


def summarize(results):
    summary = []
    for key in sorted(set((r['suite'],r['method'],r.get('target',''),r.get('budget',0)) for r in results)):
        selected = [r for r in results if (r['suite'],r['method'],r.get('target',''),r.get('budget',0))==key]
        metrics = ('mape_pct','mae_us','spearman','regret_b1','regret_b2','regret_b4','regret_b8',
                   'success5_b1','success5_b2','success5_b4','success5_b8')
        entry = dict(zip(('suite','method','target','budget'),key))
        entry['seeds'] = len(selected)
        entry['test_tasks'] = len(selected[0]['tasks'])
        entry['metrics'] = {}
        for metric in metrics:
            # Macro-average families; within-family, average tasks. Seed SD is
            # descriptive, not a confidence interval over independent devices.
            means = []
            for run in selected:
                families = defaultdict(list)
                for task in run['tasks']:
                    if task[metric] is not None:
                        families[task['family']].append(task[metric])
                means.append(np.mean([np.mean(v) for v in families.values()]))
            entry['metrics'][metric] = {'mean': float(np.mean(means)),
                                       'seed_sd': float(np.std(means,ddof=1)) if len(means)>1 else 0.}
        entry['no_valid_top1_tasks'] = sum(t['regret_b1'] is None for r in selected for t in r['tasks'])
        summary.append(entry)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-root', type=Path, default=Path('.'))
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--seeds', type=int, nargs='+', default=[2026,2027,2028,2029,2030])
    parser.add_argument('--budgets', type=int, nargs='+', default=[32,128])
    parser.add_argument('--epochs', type=int, default=160)
    parser.add_argument('--patience', type=int, default=25)
    parser.add_argument('--batch-size', type=int, default=512)
    parser.add_argument('--lr', type=float, default=.001)
    parser.add_argument('--suite', choices=['all','a100_seven','pilot_transfer'], default='all')
    args = parser.parse_args()
    torch.set_num_threads(1)
    torch.use_deterministic_algorithms(True)
    args.output.mkdir(parents=True, exist_ok=True)
    cfg = {k:str(v) if isinstance(v,Path) else v for k,v in vars(args).items()}
    cfg.update(python=platform.python_version(), torch=torch.__version__, numpy=np.__version__,
               machine=platform.machine(), cpu_threads=1, script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
    save_json(args.output/'protocol.json',cfg)
    all_results = []
    for suite in ('a100_seven','pilot_transfer'):
        if args.suite not in ('all',suite):
            continue
        if suite == 'a100_seven':
            paths = list((args.data_root/'results/nvidia_a100-pcie-40gb').glob('*-matched30k-*.csv'))
        else:
            paths = [args.data_root/'results'/device/file for device,files in (
                ('nvidia_a100-pcie-40gb',('matmul-3557594.csv','reductions-3557594.csv',
                   'matmul-boundary-3557595.csv','reductions-boundary-3557595.csv')),
                ('nvidia_h100_pcie',('matmul-3554920.csv','reductions-3554920.csv')))
                for file in files]
        if not paths:
            raise ValueError('No input files for '+suite)
        rows, manifest = load(paths)
        if suite == 'pilot_transfer':
            keys = {device:{r['_key'] for r in rows if r['_device']==device} for device in ('A100','H100')}
            common = keys['A100'] & keys['H100']
            rows = [r for r in rows if r['_key'] in common]
            manifest['matched_attempts'] = len(rows)
            manifest['common_candidate_keys'] = len(common)
        manifest['software_versions'] = sorted(set((r.get('torch_version'),r.get('triton_version'),r.get('cuda_version')) for r in rows))
        save_json(args.output/(suite+'_manifest.json'),manifest)
        print(suite,'attempts',len(rows),'valid',sum(np.isfinite(r['_y']) for r in rows),flush=True)
        all_results.extend(run_suite(rows,suite,args))
        save_json(args.output/'summary.json',summarize(all_results))
    print('Complete:',args.output,flush=True)


if __name__ == '__main__':
    main()
